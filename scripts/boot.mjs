import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-webgl', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', (e) => console.log('pageerror:', e.message, e.stack?.split('\n').slice(0, 4).join(' | ')))
page.on('console', (m) => console.log(m.type() + ':', m.text().slice(0, 400)))
page.on('requestfailed', (r) => console.log('failed:', r.url()))
await page.goto('http://127.0.0.1:5191/?ep=7', { waitUntil: 'load' })
await page.waitForTimeout(4000)
console.log(JSON.stringify(await page.evaluate(() => ({ jop: !!window.__jop, ready: window.__jop?.stage.ready, ep: window.__jop?.show.ep?.title, st: window.__jop?.show.state }))))
await page.screenshot({ path: 'qa/boot.png' })
await browser.close()
