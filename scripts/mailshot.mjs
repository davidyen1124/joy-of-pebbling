import { chromium } from 'playwright'
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-webgl', '--ignore-gpu-blocklist'] })
for (const [name, w, h, dpr, touch] of [['desk', 1440, 900, 1, false], ['phone', 390, 844, 2, true], ['land', 844, 390, 2, true]]) {
  const ctx = await browser.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: dpr, hasTouch: touch, isMobile: touch })
  const page = await ctx.newPage()
  page.on('pageerror', (e) => console.log('pageerror:', e.message))
  await page.goto('http://127.0.0.1:5191/?ep=12', { waitUntil: 'load' })
  await page.waitForFunction(() => window.__jop && window.__jop.show.ep && window.__jop.stage.ready)
  await page.evaluate(() => document.fonts.ready)
  await page.click('#bMail')
  await page.waitForTimeout(300)
  await page.click('#optJob .chip[data-id="pirate"]')
  await page.click('#optHair .chip[data-id="beehive"]')
  await page.click('#optColor .chip[data-id="teal"]')
  await page.waitForTimeout(200)
  await page.screenshot({ path: `qa/mail-${name}.png` })
  const box = await page.evaluate(() => { const r = document.querySelector('.mail-in').getBoundingClientRect(); const f = document.querySelector('#mailSend').getBoundingClientRect(); return { w: innerWidth, h: innerHeight, top: r.top, bottom: r.bottom, left: r.left, right: r.right, sendBottom: f.bottom } })
  console.log(name, JSON.stringify(box))
  await page.click('#mailSend')
  await page.waitForTimeout(700)
  console.log(name, 'after send:', await page.evaluate(() => `${window.__jop.show.ep.title} | ${window.__jop.show.ep.blurb} | ${location.search}`))
  await ctx.close()
}
await browser.close()
